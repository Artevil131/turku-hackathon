#!/usr/bin/env python3
"""The overnight leaderboard: every experiment's `out/metrics.json` and every baseline row in one table per family.

    python3 benchmarks/overnight-2026-10-17/leaderboard.py            # from anywhere; stdlib only
    python3 benchmarks/overnight-2026-10-17/leaderboard.py --root DIR # a tree with the same layout (for tests)

Reads `experiments/*/out/metrics.json` and `benchmarks/overnight-2026-10-17/baselines/*.json` (METRICS.md "Reporting
format"; metric keys in harness-spec.md), and each experiment's README frontmatter `status:`. Writes

  - README.md: only the text between the two leaderboard markers is replaced; everything else (the morning report the
    orchestrator writes around it) is kept. A missing file, or one with no markers, gets a skeleton or the markers.
  - full-table.md: every flattened metric key for every row, one table per family.

Rows: baselines first, then untuned experiments, then rows tuned on the scoring period, each group by name. The best
value per column among untuned non-baseline rows is bold. Runtime (`runtime_s`, `cpu_s`) is shown for information and is
never marked, ranked or sorted on. Experiments whose README says `status: rejected` are listed apart, not ranked. The
output has no timestamps, so a rerun on the same files gives the same bytes.
"""

