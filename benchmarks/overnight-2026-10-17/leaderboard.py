@dataclass
class Row:
    name: str
    path: Path  # the metrics.json
    link: Path  # what the row links to: the experiment directory, or the baseline file
    doc: dict
    baseline: bool
    status: str | None
    flat: dict = field(default_factory=dict)
    intervals: dict = field(default_factory=dict)

    @property
    def family(self) -> str:
        return str(self.doc.get("family", "other"))

    @property
    def tuned(self) -> bool:
        return bool(self.doc.get("tuned_on_test", False))

    @property
    def rejected(self) -> bool:
        return self.status == "rejected"

    @property
    def marks(self) -> str:
        out = []
        if self.baseline:
            out.append("baseline")
        if self.tuned:
            out.append("tuned on test")
        if self.status not in (None, "accepted"):
            out.append(self.status)
        return ", ".join(out)

    @property
    def eligible(self) -> bool:
        """May carry the best mark: untuned, not a baseline, not rejected."""
        return not (self.baseline or self.tuned or self.rejected)


def flatten(obj: object, prefix: str = "") -> dict[str, object]:
    """Nested dicts to dotted keys, sorted; anything else (numbers, strings, lists, null) is a leaf."""
    if isinstance(obj, dict):
        out: dict[str, object] = {}
        for k in sorted(obj, key=str):
            out.update(flatten(obj[k], f"{prefix}.{k}" if prefix else str(k)))
        return out
    return {prefix: obj}


def read_status(readme: Path) -> str | None:
    """`status:` from the README's frontmatter (text after # on the line is a comment), lower-cased."""
    try:
        text = readme.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    m = re.match(r"\ufeff?---[ \t]*\n(.*?)\n---", text, re.S)
    if not m:
        return None
    for line in m.group(1).splitlines():
        s = re.match(r"\s*status\s*:\s*([A-Za-z_-]+)", line)
        if s:
            return s.group(1).lower()
    return None


def load_row(path: Path, link: Path, baseline: bool, status: str | None) -> Row:
    doc = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict) or not isinstance(doc.get("metrics"), dict):
        raise ValueError("no metrics object")
    name = str(doc.get("experiment") or (path.stem if baseline else path.parent.parent.name))
    row = Row(name, path, link, doc, baseline, status)
    row.flat = flatten(doc["metrics"])
    iv = doc.get("intervals")
    row.intervals = flatten(iv) if isinstance(iv, dict) else {}
    return row


def collect(root: Path) -> tuple[list[Row], list[tuple[str, Path, str]], list[tuple[Path, str]]]:
    """(rows, rejected records without metrics: (name, directory, status), unreadable files: (path, why))."""
    rows: list[Row] = []
    unreadable: list[tuple[Path, str]] = []
    base_dir = root / "benchmarks" / "overnight-2026-10-17" / "baselines"
    for p in sorted(base_dir.glob("*.json")):
        try:
            rows.append(load_row(p, p, True, None))
        except (OSError, ValueError) as e:  # json.JSONDecodeError is a ValueError
            unreadable.append((p, str(e)))
    no_metrics: list[tuple[str, Path, str]] = []
    for d in sorted((root / "experiments").glob("*/")):
        if not d.is_dir():
            continue
        status = read_status(d / "README.md")
        p = d / "out" / "metrics.json"
        if p.exists():
            try:
                rows.append(load_row(p, d, False, status))
            except (OSError, ValueError) as e:
                unreadable.append((p, str(e)))
        else:
            m = re.match(r"(\d{4})-", d.name)
            if status == "rejected" and m and int(m.group(1)) >= FIRST_EXPERIMENT:
                no_metrics.append((d.name, d, status))
    return rows, no_metrics, unreadable


def ordered(rows: list[Row]) -> list[Row]:
    """Baselines, then untuned, then tuned on test; each group by name. Never by any metric or runtime."""
    group = lambda r: 0 if r.baseline else (2 if r.tuned else 1)
    return sorted(rows, key=lambda r: (group(r), r.name))


# ---------------------------------------------------------------------------------------------------------------------
# Formatting
# ---------------------------------------------------------------------------------------------------------------------


def is_num(v: object) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


def fmt_num(x: float) -> str:
    if float(x).is_integer() and abs(x) >= 1:
        return str(int(x))
    a = abs(x)
    if a == 0:
        return "0"
    if a >= 100:
        return f"{x:.0f}"
    if a >= 10:
        return f"{x:.1f}"
    if a >= 1:
        return f"{x:.2f}"
    if a >= 0.1:
        return f"{x:.3f}"
    if a >= 0.01:
        return f"{x:.4f}"
    return f"{x:.3g}" if a >= 1e-4 else f"{x:.2e}"


def fmt_value(v: object) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if is_num(v):
        return fmt_num(float(v))
    if isinstance(v, float):  # nan or inf
        return "n/a"
    if isinstance(v, str):
        return v
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def fmt_interval(iv: object) -> str:
    if isinstance(iv, list) and len(iv) == 2 and all(is_num(x) for x in iv):
        lo, hi = fmt_num(float(iv[0])), fmt_num(float(iv[1]))
        return f" ({lo} to {hi})" if "-" in lo + hi else f" ({lo}–{hi})"
    return ""


def escape(s: object) -> str:
    return str(s).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").strip()


def link_to(row: Row, out_dir: Path, label: str | None = None) -> str:
    rel = os.path.relpath(row.link, out_dir).replace(os.sep, "/")
    if row.link.is_dir():
        rel += "/"
    return f"[{escape(label or row.name)}]({rel})"


def d1_cell(row: Row) -> str:
    parts = [fmt_value(row.flat[k]) if k in row.flat else "–" for k in ("D1.E1", "D1.E2", "D1.E3", "D1.E4")]
    return "–" if all(p == "–" for p in parts) else " / ".join(parts)


def best_values(rows: list[Row], col: Col) -> float | None:
    vals = [r.flat[col.key] for r in rows if r.eligible and is_num(r.flat.get(col.key))]
    if not vals or col.direction == "none":
        return None
    if col.direction == "lower":
        return min(vals)
    if col.direction == "higher":
        return max(vals)
    if col.direction.startswith("target:"):
        target = float(col.direction.split(":", 1)[1])
        return min(vals, key=lambda v: abs(v - target))
    return None


def cell(row: Row, col: Col, best: float | None) -> str:
    if col.kind == "d1":
        return d1_cell(row)
    if col.key not in row.flat:
        return "–"
    v = row.flat[col.key]
    text = fmt_value(v)
    if best is not None and row.eligible and is_num(v) and math.isclose(float(v), best, rel_tol=1e-9, abs_tol=1e-12):
        text = f"**{text}**"
    return text + (fmt_interval(row.intervals.get(col.key)) if is_num(v) else "")


def arrow(col: Col) -> str:
    return {"lower": " ↓", "higher": " ↑"}.get(col.direction, "")


def table(header: list[str], body: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in body]
    return lines


def runtime(row: Row, key: str) -> str:
    """Seconds with one decimal; for information only."""
    v = row.doc.get(key)
    if not is_num(v):
        return "–"
    return f"{v:.0f}" if v >= 100 or float(v).is_integer() else f"{v:.1f}"


# ---------------------------------------------------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------------------------------------------------


def family_table(family: str, rows: list[Row], out_dir: Path) -> list[str]:
    cols = [c for c in COLUMNS.get(family, []) if not c.optional or any(c.key in r.flat for r in rows)]
    best = {c.key: best_values(rows, c) for c in cols}
    header = ["Row", "Mark", *[c.label + arrow(c) for c in cols], "runtime_s", "cpu_s", "Method"]
    body = [
        [link_to(r, out_dir), escape(r.marks), *[cell(r, c, best[c.key]) for c in cols], runtime(r, "runtime_s"), runtime(r, "cpu_s"), escape(r.doc.get("method", ""))]
        for r in rows
    ]
    return table(header, body)


def build_block(rows: list[Row], no_metrics: list[tuple[str, Path, str]], unreadable: list[tuple[Path, str]], out_dir: Path) -> str:
    lines: list[str] = []
    live = [r for r in ordered(rows) if not r.rejected]
    rejected = [r for r in ordered(rows) if r.rejected]
    n_base = sum(r.baseline for r in live)
    n_tuned = sum(r.tuned and not r.baseline for r in live)
    lines += [
        f"{len(live)} rows ({n_base} baselines, {len(live) - n_base - n_tuned} untuned, {n_tuned} tuned on test); "
        f"{len(rejected) + len(no_metrics)} rejected.",
        "",
        LEGEND,
        "",
    ]
    for fam in FAMILIES:
        sub = [r for r in live if r.family == fam]
        lines += [f"### {fam.capitalize()}", ""]
        for note in FAMILY_NOTES.get(fam, []):
            lines += [note, ""]
        if sub:
            lines += family_table(fam, sub, out_dir) + [""]
        else:
            lines += ["No rows yet.", ""]
    other = [r for r in live if r.family not in FAMILIES]
    if other:
        lines += ["### Other families", ""]
        lines += table(["Row", "Mark", "Family", "Method"], [[link_to(r, out_dir), escape(r.marks), escape(r.family), escape(r.doc.get("method", ""))] for r in other]) + [""]
    if rejected or no_metrics:
        lines += ["### Rejected (not ranked)", ""]
        for r in rejected:
            lines.append(f"- {link_to(r, out_dir)} ({escape(r.family)}): {escape(r.doc.get('method', ''))}")
        for name, d, _ in no_metrics:
            lines.append(f"- [{name}]({os.path.relpath(d, out_dir).replace(os.sep, '/')}/): no metrics.json")
        lines.append("")
    if unreadable:
        lines += ["### Unreadable files (skipped)", ""]
        lines += [f"- `{os.path.relpath(p, out_dir).replace(os.sep, '/')}`: {escape(why)}" for p, why in sorted(unreadable)] + [""]
    return "\n".join(lines).rstrip() + "\n"


def build_full(rows: list[Row], out_dir: Path) -> str:
    lines = [
        "# Overnight leaderboard, every metric",
        "",
        "Every flattened metric key (dotted path into `metrics`) for every row, by family; values with their 95 % interval where "
        "metrics.json has one, `–` where the row does not produce the key, `n/a` where it is null. Generated by `leaderboard.py`; "
        "rejected rows are included and marked. Runtime is for information only.",
        "",
    ]
    for fam in [*FAMILIES, "other"]:
        sub = [r for r in ordered(rows) if (r.family == fam if fam != "other" else r.family not in FAMILIES)]
        if not sub:
            continue
        keys = sorted({k for r in sub for k in r.flat})
        header = ["key", *[link_to(r, out_dir) for r in sub]]
        body = [
            ["mark", *[escape(r.marks) for r in sub]],
            ["method", *[escape(r.doc.get("method", "")) for r in sub]],
            ["runtime_s", *[runtime(r, "runtime_s") for r in sub]],
            ["cpu_s", *[runtime(r, "cpu_s") for r in sub]],
        ]
        for k in keys:
            vals = []
            for r in sub:
                if k not in r.flat:
                    vals.append("–")
                else:
                    v = r.flat[k]
                    vals.append(escape(fmt_value(v) + (fmt_interval(r.intervals.get(k)) if is_num(v) else "")))
            body.append([escape(k), *vals])
        lines += [f"## {fam.capitalize()}", ""] + table(header, body) + [""]
    return "\n".join(lines).rstrip() + "\n"


def skeleton(block_text: str) -> str:
    return (
        f"# {TITLE}\n\n{INTRO}\n\n{START}\n{block_text}{END}\n\n## Morning report\n\n(written at the end of the run)\n"
    )


def splice(existing: str, block_text: str) -> str:
    """Put the block between the markers, keeping every other character; with no markers, insert them after the title."""
    wrapped = f"{START}\n{block_text}{END}"
    i, j = existing.find(START), existing.find(END)
    if i != -1 and j != -1 and i < j:
        return existing[:i] + wrapped + existing[j + len(END) :]
    print("leaderboard: markers not found in README.md; inserted after the title", file=sys.stderr)
    m = re.search(r"^# .*\n(\n)?", existing, re.M)
    at = m.end() if m else 0
    return existing[:at] + f"{wrapped}\n\n" + existing[at:]


def main(argv: list[str] | None = None) -> int:
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=here.parents[1], help="repository root (default: this script's)")
    ap.add_argument("--dry-run", action="store_true", help="print the block instead of writing files")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    out_dir = root / "benchmarks" / "overnight-2026-10-17"
    rows, no_metrics, unreadable = collect(root)
    block_text = build_block(rows, no_metrics, unreadable, out_dir)
    if args.dry_run:
        print(block_text)
        return 0
    out_dir.mkdir(parents=True, exist_ok=True)
    readme = out_dir / "README.md"
    new = splice(readme.read_text(encoding="utf-8"), block_text) if readme.exists() else skeleton(block_text)
    if not readme.exists() or readme.read_text(encoding="utf-8") != new:
        readme.write_text(new, encoding="utf-8")
    full = build_full(rows, out_dir)
    full_path = out_dir / "full-table.md"
    if not full_path.exists() or full_path.read_text(encoding="utf-8") != full:
        full_path.write_text(full, encoding="utf-8")
    print(f"leaderboard: {len(rows)} rows, {len(no_metrics)} rejected without metrics, {len(unreadable)} unreadable -> {readme}, {full_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
